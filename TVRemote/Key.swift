/// Android KEYCODE_* values.
enum Key: Int, CaseIterable, Sendable {
    case power = 26, home = 3, back = 4
    case up = 19, down = 20, left = 21, right = 22, ok = 23
    case volumeUp = 24, volumeDown = 25, mute = 164
    case playPause = 85, rewind = 89, fastForward = 90
    case input = 178, settings = 176
}
